CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  pass_hash VARCHAR(255) NOT NULL,
  name VARCHAR(120) NOT NULL DEFAULT '',
  email_verified TINYINT NOT NULL DEFAULT 0,
  verify_token VARCHAR(64) NULL, verify_expires BIGINT NULL,
  reset_token VARCHAR(64) NULL, reset_expires BIGINT NULL,
  settings MEDIUMTEXT NOT NULL,
  access_override VARCHAR(10) NOT NULL DEFAULT 'auto',
  created_at BIGINT NOT NULL, last_login BIGINT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS families (
  id VARCHAR(32) PRIMARY KEY, name VARCHAR(120) NOT NULL DEFAULT '', owner_id BIGINT UNSIGNED NOT NULL,
  mode VARCHAR(10) NOT NULL DEFAULT 'self', settings MEDIUMTEXT NOT NULL, created_at BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS members (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  family_id VARCHAR(32) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  role VARCHAR(10) NOT NULL,
  student_id VARCHAR(32) NULL, created_at BIGINT NOT NULL,
  UNIQUE KEY u_user (user_id),
  KEY ix_fam (family_id),
  CONSTRAINT fk_m_fam FOREIGN KEY (family_id) REFERENCES families(id) ON DELETE CASCADE,
  CONSTRAINT fk_m_usr FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS students (
  id VARCHAR(32) PRIMARY KEY, family_id VARCHAR(32) NOT NULL,
  name VARCHAR(120) NOT NULL, level VARCHAR(80) NULL, institution VARCHAR(160) NULL, grade VARCHAR(40) NULL, division VARCHAR(40) NULL, shift VARCHAR(40) NULL,
  tz VARCHAR(60) NOT NULL DEFAULT 'UTC', settings MEDIUMTEXT NOT NULL,
  created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, deleted_at BIGINT NULL,
  KEY ix_fam (family_id),
  CONSTRAINT fk_s_fam FOREIGN KEY (family_id) REFERENCES families(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS records (
  id VARCHAR(32) PRIMARY KEY, family_id VARCHAR(32) NOT NULL,
  student_id VARCHAR(32) NULL, type VARCHAR(20) NOT NULL, data MEDIUMTEXT NOT NULL,
  visibility VARCHAR(10) NOT NULL DEFAULT 'family',
  created_by BIGINT NULL, updated_by BIGINT NULL,
  created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, deleted_at BIGINT NULL,
  KEY rec_sync (family_id, updated_at),
  KEY rec_type (family_id, student_id, type),
  CONSTRAINT fk_r_fam FOREIGN KEY (family_id) REFERENCES families(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS invites (
  code VARCHAR(20) PRIMARY KEY, family_id VARCHAR(32) NOT NULL,
  role VARCHAR(10) NOT NULL, student_id VARCHAR(32) NULL, created_by BIGINT NULL,
  expires_at BIGINT NOT NULL, used_by BIGINT NULL, used_at BIGINT NULL, revoked TINYINT NOT NULL DEFAULT 0,
  CONSTRAINT fk_i_fam FOREIGN KEY (family_id) REFERENCES families(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS files (
  id VARCHAR(32) PRIMARY KEY, family_id VARCHAR(32) NOT NULL,
  student_id VARCHAR(32) NULL, record_id VARCHAR(32) NULL, name VARCHAR(200) NOT NULL, mime VARCHAR(100) NOT NULL, size BIGINT NOT NULL,
  path VARCHAR(255) NOT NULL, uploaded_by BIGINT NULL, created_at BIGINT NOT NULL,
  KEY ix_fam (family_id),
  CONSTRAINT fk_f_fam FOREIGN KEY (family_id) REFERENCES families(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reminders (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  family_id VARCHAR(32) NOT NULL, record_id VARCHAR(32) NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
  rkey VARCHAR(80) NOT NULL, category VARCHAR(30) NOT NULL, send_at BIGINT NOT NULL,
  payload MEDIUMTEXT NOT NULL, status VARCHAR(12) NOT NULL DEFAULT 'pending',
  tries INT NOT NULL DEFAULT 0, last_error VARCHAR(255) NULL, sent_at BIGINT NULL, created_at BIGINT NOT NULL,
  UNIQUE KEY u_rem (record_id, user_id, rkey),
  KEY rem_due (status, send_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mail_log (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT NULL, to_email VARCHAR(190), kind VARCHAR(30),
  status VARCHAR(12), error VARCHAR(255) NULL, created_at BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS digests (user_id BIGINT UNSIGNED NOT NULL, dkey VARCHAR(40) NOT NULL, status VARCHAR(12) NOT NULL DEFAULT 'sent', tries INT NOT NULL DEFAULT 0, sent_at BIGINT NULL, PRIMARY KEY(user_id, dkey)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rate (bucket VARCHAR(120) NOT NULL, ts BIGINT NOT NULL, KEY rate_b (bucket, ts)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS subscriptions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  preapproval_id VARCHAR(80) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NULL,
  payer_email VARCHAR(190) NOT NULL DEFAULT '',
  status VARCHAR(12) NOT NULL DEFAULT 'pending',
  reason VARCHAR(255) NOT NULL DEFAULT '',
  amount_cent BIGINT NOT NULL DEFAULT 0, currency VARCHAR(8) NOT NULL DEFAULT 'ARS', period_days INT NOT NULL DEFAULT 30,
  next_charge BIGINT NULL, created BIGINT NOT NULL, updated BIGINT NOT NULL,
  KEY ix_user (user_id), KEY ix_email (payer_email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payments (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  mp_id VARCHAR(80) NOT NULL UNIQUE, preapproval_id VARCHAR(80) NOT NULL,
  status VARCHAR(16) NOT NULL, detail VARCHAR(120) NOT NULL DEFAULT '', amount_cent BIGINT NOT NULL DEFAULT 0, currency VARCHAR(8) NOT NULL DEFAULT 'ARS',
  retry INT NOT NULL DEFAULT 0, debit_date BIGINT NULL, created BIGINT NOT NULL, updated BIGINT NOT NULL,
  KEY ix_pre (preapproval_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS orders (
  id VARCHAR(32) PRIMARY KEY,
  status VARCHAR(12) NOT NULL DEFAULT 'pending',
  mp_payment_id VARCHAR(80) NULL, preference_id VARCHAR(120) NULL,
  payer_email VARCHAR(190) NOT NULL DEFAULT '', amount_cent BIGINT NOT NULL DEFAULT 0,
  license_id BIGINT UNSIGNED NULL, created BIGINT NOT NULL, updated BIGINT NOT NULL,
  KEY ix_pay (mp_payment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS licenses (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  license_key VARCHAR(24) NOT NULL UNIQUE, email VARCHAR(190) NOT NULL DEFAULT '', order_id VARCHAR(32) NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'active', max_devices INT NOT NULL DEFAULT 3, origin VARCHAR(12) NOT NULL DEFAULT 'compra', note VARCHAR(120) NOT NULL DEFAULT '',
  created BIGINT NOT NULL, KEY ix_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS devices (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  license_id BIGINT UNSIGNED NOT NULL, device_id VARCHAR(64) NOT NULL, label VARCHAR(120) NOT NULL DEFAULT '',
  active TINYINT NOT NULL DEFAULT 1, first_seen BIGINT NOT NULL, last_seen BIGINT NOT NULL,
  UNIQUE KEY u_dev (license_id, device_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mp_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, received BIGINT NOT NULL, topic VARCHAR(60), data_id VARCHAR(80), sig_ok TINYINT NOT NULL DEFAULT 0, result VARCHAR(20), detail VARCHAR(255)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ts BIGINT NOT NULL, actor VARCHAR(190), action VARCHAR(60), detail VARCHAR(255), ip VARCHAR(45)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS landing_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ts BIGINT NOT NULL, day DATE NOT NULL, type VARCHAR(20) NOT NULL, visitor CHAR(16) NOT NULL,
  source VARCHAR(60) NOT NULL DEFAULT '', campaign VARCHAR(60) NOT NULL DEFAULT '', device VARCHAR(8) NOT NULL DEFAULT '', detail VARCHAR(40) NOT NULL DEFAULT '',
  KEY ix_day_type (day, type), KEY ix_vis (visitor, day, ts)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
